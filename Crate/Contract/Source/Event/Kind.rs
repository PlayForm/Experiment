//! The 87 signed event kinds.
//!
//! `events/catalog.json` lists 87 authoritative kinds: 57 canonical
//! (`EVENT_INDEX.md:43-108`, `docs/05-event-correspondence.md:43-108`) and 30
//! v6.1 additions (custody, license, feedback, knowledge, audit and curriculum
//! families). Every kind is trusted-software-only; a model never subscribes
//! (`EVENT_INDEX.md:3-4`).
//!
//! House-style exception: each variant mirrors its `event_kind` wire string
//! byte-for-byte. Splitting a compound kind into a path would rename the very
//! identifier the catalog publishes.

